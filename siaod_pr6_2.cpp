#include <iostream>
#include <vector>
#include <string>
using namespace std;

// Построение таблицы сдвигов по эвристике хорошего суффикса
vector<int> buildGoodSuffixTable(const string& pat) {
    int m = pat.length();
    vector<int> shift(m + 1, 0); // shift[i] - на сколько сдвинуть шаблон, если несовпадение
    // произошло на позиции i-1 (shift[0] - сдвиг после полного совпадения)
    vector<int> f(m + 1, 0); // f[i] - начало самой правой копии суффикса образца или его части

    // Шаг 1: вычисление массива f (справа налево)
    int i = m, j = m + 1;
    f[i] = j; // для пустого суффикса (после конца шаблона) указываем за пределы
    while (i > 0) {
        // Ищем подходящую копию суффикса - символы перед суффиксами образца и текста должны отличаться
        while (j <= m && pat[i - 1] != pat[j - 1]) {
            // Если нашли различие перед суффиксами, запоминаем сдвиг для позиции j
            if (shift[j] == 0) {
                shift[j] = j - i; // сдвиг = разница позиций между копиями суффиксов
            }
            j = f[j]; // переходим к следующей возможной копии суффикса по цепочке
        }
        i--;
        j--;
        f[i] = j; // записываем найденную позицию копии для суффикса pat[i..m-1]
    }

    // Шаг 2: заполнение оставшихся значений shift
    j = f[0]; // начинаем с грани самого длинного суффикса (всего шаблона)
    for (i = 0; i <= m; i++) {
        // Если сдвиг для i еще не задан, используем текущую грань j
        if (shift[i] == 0) {
            shift[i] = j; // устанавливаем сдвиг равный позиции грани
        }
        // Если дошли до текущей грани, переходим к следующей (более короткой) грани
        if (i == j) {
            j = f[j]; // переходим по цепочке граней
        }
    }

    return shift;
}

// Поиск всех вхождений с использованием только эвристики хорошего суффикса
vector<int> boyerMooreGoodSuffix(const string& text, const string& pattern) {
    if (pattern.empty()) return {};
    int n = text.length();
    int m = pattern.length();
    vector<int> shift = buildGoodSuffixTable(pattern); // строим таблицу сдвигов
    vector<int> result;
    int s = 0; // текущая позиция выравнивания шаблона с текстом

    while (s <= n - m) {
        int j = m - 1; // начинаем сравнение с конца шаблона
        // Сравниваем шаблон с текстом справа налево
        while (j >= 0 && pattern[j] == text[s + j]) {
            j--; // двигаемся к началу пока символы совпадают
        }
        if (j < 0) {
            // Полное совпадение - весь шаблон совпал с текстом
            result.push_back(s); // сохраняем позицию совпадения
            s += shift[0]; // сдвигаем шаблон для поиска следующего вхождения
        } else {
            // Несовпадение на позиции j - используем таблицу сдвигов
            // shift[j+1] потому что shift[i] соответствует несовпадению ЛЕВЕЕ i
            s += shift[j + 1]; // умный сдвиг на основе уже совпавшего суффикса
        }
    }
    return result;
}

int main() {
    string text, pattern;
    cout << "Введите текст: ";
    getline(cin, text);
    cout << "Введите образец: ";
    getline(cin, pattern);

    vector<int> positions = boyerMooreGoodSuffix(text, pattern);

    if (positions.empty()) {
        cout << "Подстрока не найдена.\n";
    } else {
        cout << "Найдено на позициях: ";
        for (int pos : positions) {
            cout << pos << " ";
        }
        cout << endl;
    }

    return 0;
}